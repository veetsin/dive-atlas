/**
 * Copy text with the fallbacks the WeChat webviews need: the async clipboard API is
 * missing or rejects on many Android builds, so fall back to a temporary textarea +
 * execCommand. Returns false when neither works, so the caller can show the text to
 * long-press instead. Must be called from inside a user gesture.
 */
export async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    /* fall through to the legacy path */
  }
  try {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.setAttribute('readonly', '');
    ta.style.position = 'fixed';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.select();
    ta.setSelectionRange(0, text.length);
    const ok = document.execCommand('copy');
    ta.remove();
    return ok;
  } catch {
    return false;
  }
}
